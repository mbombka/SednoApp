#!/usr/bin/env python3
"""Generate translated in-app policies and Markdown from versioned JSON sources."""
import argparse
import json
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    documents = {}
    for source in sorted((ROOT / 'docs').glob('privacy-policy.*.json')):
        language = source.name.split('.')[1]
        if language == 'pl':
            continue  # Existing Polish publication generator owns this source.
        policy = json.loads(source.read_text())
        assert policy['version'] and policy['aiNotice'] and policy['deletionNotice']
        literal = lambda value: json.dumps(value, ensure_ascii=False).replace('$', r'\$')
        name = 'PrivacyPolicy' + language.title()
        dart = "// Generated by tools/generate_privacy_translations.py.\n"
        dart += "import 'privacy_policy.dart';\n\nabstract final class " + name + " {\n"
        for key in ('version', 'versionLabel', 'aiNotice', 'deletionNotice'):
            dart += f'  static const {key} = {literal(policy[key])};\n'
        dart += '  static const sections = <PrivacySection>[\n'
        sections = policy['sections'] + [{
            'title': 'Sources and provider terms',
            'paragraphs': [item['title'] + ': ' + item['url'] for item in policy['sources']],
        }]
        for section in sections:
            dart += f"    PrivacySection({literal(section['title'])}, [\n"
            dart += ''.join(f'      {literal(text)},\n' for text in section['paragraphs'])
            dart += '    ]),\n'
        dart += '  ];\n}\n'
        with tempfile.TemporaryDirectory(prefix='sedno-policy-translation-') as directory:
            temporary = Path(directory) / f'privacy_policy_{language}.dart'
            temporary.write_text(dart)
            subprocess.run(['dart', 'format', str(temporary)], check=True, stdout=subprocess.DEVNULL)
            dart = temporary.read_text()
        documents[f'mobile/lib/features/privacy/domain/privacy_policy_{language}.dart'] = dart
        markdown = f"# {policy['title']}\n\nVersion: {policy['versionLabel']}\n\n"
        for section in sections:
            markdown += f"## {section['title']}\n\n" + '\n\n'.join(section['paragraphs']) + '\n\n'
        documents[f'docs/privacy-policy.{language}.md'] = markdown
    return documents


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, content in generate().items():
        path = ROOT / name
        if args.check:
            actual = path.read_text() if path.exists() else ''
            if actual != content:
                stale.append(name)
        else:
            path.write_text(content)
    if stale:
        raise SystemExit('Stale translated policies: ' + ', '.join(stale))
