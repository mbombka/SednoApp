#!/usr/bin/env python3
"""Generate the app and publication documents from one versioned policy."""
import argparse
import html
import json
from pathlib import Path
import subprocess
import tempfile
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


def literal(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')


def generate():
    policy = json.loads((ROOT / 'docs/privacy-policy.pl.json').read_text())
    sections = policy['sections']
    assert all(s['title'] and s['paragraphs'] for s in sections)
    for key in ('website', 'privacyUrl', 'deletionUrl'):
        url = urlsplit(policy[key])
        assert url.scheme == 'https' and url.netloc in ('sedno.xyz', 'www.sedno.xyz')
    text = json.dumps(policy, ensure_ascii=False)
    assert not any(marker in text for marker in ('DO PODANIA', 'DO POTWIERDZENIA', 'DO UZUPEŁNIENIA'))
    md = f"# {policy['title']}\n\nWersja: {policy['versionLabel']}\n\n"
    for section in sections:
        md += f"## {section['title']}\n\n" + '\n\n'.join(section['paragraphs']) + '\n\n'
    md += '## Źródła i warunki dostawców\n\n'
    md += '\n'.join(f"- [{s['title']}]({s['url']})" for s in policy['sources']) + '\n'
    dart = '// Generated by tools/generate_privacy_policy.py. Edit docs/privacy-policy.pl.json.\n'
    dart += 'abstract final class PrivacyPolicy {\n'
    for key in ('version', 'versionLabel', 'aiNotice', 'deletionNotice'):
        dart += f'  static const {key} = {literal(policy[key])};\n'
    dart += '  static const sections = <PrivacySection>[\n'
    for section in sections + [{'title': 'Źródła i warunki dostawców', 'paragraphs': [s['title'] + ': ' + s['url'] for s in policy['sources']]}]:
        dart += f"    PrivacySection({literal(section['title'])}, [\n"
        dart += ''.join(f'      {literal(p)},\n' for p in section['paragraphs'])
        dart += '    ]),\n'
    dart += '  ];\n}\n\nclass PrivacySection {\n  const PrivacySection(this.title, this.paragraphs);\n\n  final String title;\n  final List<String> paragraphs;\n}\n'
    info = '// Generated by tools/generate_privacy_policy.py. Edit docs/privacy-policy.pl.json.\nabstract final class AppInformation {\n'
    for key, source in [('website', 'website'), ('contact', 'email'), ('privacyUrl', 'privacyUrl'), ('deletionUrl', 'deletionUrl')]:
        info += f'  static const {key} = {literal(policy[source])};\n'
    info += '}\n'
    # Use the repository's Dart formatter so generated files pass the same checks.
    with tempfile.TemporaryDirectory(prefix='sedno-policy-') as temp:
        paths = [Path(temp) / 'privacy_policy.dart', Path(temp) / 'app_information.dart']
        for path, value in zip(paths, [dart, info]):
            path.write_text(value)
        subprocess.run(['dart', 'format', *map(str, paths)], check=True, stdout=subprocess.DEVNULL)
        dart, info = (p.read_text() for p in paths)

    def page(title, selected, deletion=False):
        esc = html.escape
        body = ''.join('<section><h2>' + esc(s['title']) + '</h2>' + ''.join('<p>' + esc(p) + '</p>' for p in s['paragraphs']) + '</section>' for s in selected)
        if deletion:
            body = '<p><a href="mailto:' + esc(policy['email'], quote=True) + '?subject=Usuni%C4%99cie%20konta%20Sedno">Wyślij prośbę o usunięcie konta</a></p>' + body
        sources = '<ul>' + ''.join('<li><a href="' + esc(s['url'], quote=True) + '">' + esc(s['title']) + '</a></li>' for s in policy['sources']) + '</ul>'
        return f'''<!doctype html>
<!-- Generated by tools/generate_privacy_policy.py. -->
<html lang="pl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(title)}</title>
<style>body{{margin:0;background:#fff;color:#14243a;font:1.125rem/1.65 system-ui}}main{{max-width:46rem;margin:auto;padding:24px;overflow-wrap:anywhere}}a{{color:#0057b7;display:inline-block;min-height:48px}}h1,h2{{line-height:1.3}}nav{{display:flex;flex-wrap:wrap;gap:16px}}:focus-visible{{outline:3px solid #0057b7;outline-offset:3px}}</style></head>
<body><main><nav aria-label="Informacje o Sedno"><a href="{esc(policy['website'])}">Sedno</a><a href="{esc(policy['privacyUrl'])}">Prywatność i dane</a><a href="{esc(policy['deletionUrl'])}">Usuwanie konta</a></nav>
<h1>{esc(title)}</h1><p>Wersja: <time datetime="{policy['version']}">{esc(policy['versionLabel'])}</time></p>
{body}<h2>Źródła i warunki dostawców</h2>{sources}</main></body></html>
'''
    return {
        'docs/privacy-policy.pl.md': md,
        'mobile/lib/features/privacy/domain/privacy_policy.dart': dart,
        'mobile/lib/app/app_information.dart': info,
        'docs/public/prywatnosc/index.html': page(policy['title'], sections),
        'docs/public/usun-konto/index.html': page('Sedno — usunięcie konta i danych', [sections[i] for i in (0, 2, 8, 9, 10)], True),
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, content in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit('Nieaktualne dokumenty: ' + ', '.join(stale))
    print('Dokumenty prywatności są spójne.' if args.check else 'Wygenerowano dokumenty prywatności.')
